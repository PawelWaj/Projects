#!/usr/bin/env python3
"""Generates docs/OSB_CamelK_Workflow.drawio: two separated tracks (A migration, B testing+mocking) that meet only at
verification. Rerun after edits: python3 docs/build_workflow_drawio.py"""
import html
from pathlib import Path

INK, MINT, GREY, TMINT, TGREY = "#06041F", "#47D7AC", "#8893A5", "#EAF9F4", "#EEF1F4"
BLUE_F, BLUE_L = "#E8F0FE", "#4A7BD0"      # track A
AMB_F, AMB_L = "#FFF4DC", "#F5B942"        # human gates
cells, nid = [], [10]


def new_id():
    nid[0] += 1
    return f"c{nid[0]}"


def box(x, y, w, h, text, fill, line, fs=12, bold=False, fc=INK, rounded=1, dashed=0, align="center"):
    i = new_id()
    style = (f"rounded={rounded};whiteSpace=wrap;html=1;fillColor={fill};strokeColor={line};fontColor={fc};"
             f"fontSize={fs};fontStyle={1 if bold else 0};arcSize=8;dashed={dashed};align={align};verticalAlign=middle;spacing=6;")
    cells.append(f'<mxCell id="{i}" value="{html.escape(text)}" style="{style}" vertex="1" parent="1">'
                 f'<mxGeometry x="{x}" y="{y}" width="{w}" height="{h}" as="geometry"/></mxCell>')
    return i


def text(x, y, w, h, t, fs=13, bold=True, fc=INK, align="left"):
    i = new_id()
    cells.append(f'<mxCell id="{i}" value="{html.escape(t)}" style="text;html=1;fontSize={fs};fontStyle={1 if bold else 0};'
                 f'fontColor={fc};align={align};verticalAlign=middle;whiteSpace=wrap;" vertex="1" parent="1">'
                 f'<mxGeometry x="{x}" y="{y}" width="{w}" height="{h}" as="geometry"/></mxCell>')


def edge(a, b, color=INK, label="", dashed=0, ports="", points=()):
    i = new_id()
    pts = ("<Array as=\"points\">" + "".join(f'<mxPoint x="{x}" y="{y}"/>' for x, y in points) + "</Array>") if points else ""
    cells.append(f'<mxCell id="{i}" value="{html.escape(label)}" style="edgeStyle=orthogonalEdgeStyle;rounded=1;html=1;'
                 f'strokeColor={color};strokeWidth=2;endArrow=block;endFill=1;fontSize=11;fontColor={color};dashed={dashed};'
                 f'labelBackgroundColor=#FFFFFF;{ports}" edge="1" parent="1" source="{a}" target="{b}">'
                 f'<mxGeometry relative="1" as="geometry">{pts}</mxGeometry></mxCell>')


W = 1900
text(30, 15, W - 60, 40, "OSB to Camel K: two separate tracks, generated by pi agents, joined only at verification", fs=22)
text(30, 55, W - 60, 28, "Track A writes the code. Track B decides what correct means. The implementer never writes tests; "
     "the tester never sees the route; every expected value comes from OSB.", fs=13, bold=False, fc=GREY)

# lanes
box(20, 100, W - 40, 300, "", "#F7F9FF", BLUE_L, dashed=1)
text(40, 108, 900, 26, "TRACK A — MIGRATION: OSB code → Camel K route", fs=15, fc=BLUE_L)
box(20, 430, W - 40, 300, "", TMINT, MINT, dashed=1)
text(40, 438, 900, 26, "TRACK B — TESTING AND MOCKING: OSB logs + OSB logic → tests and mocks", fs=15, fc="#0E6B50")

# Track A
a1 = box(50, 160, 220, 100, "OSB source code\n(OSB repository: project, proxy,\npipeline, .bix, XQuery, WSDL/XSD)", TGREY, GREY, 12)
a2 = box(320, 160, 230, 100, "1 Inventory + flow card\nosb_inventory.py · scaffold_flow.py\n(every branch, interface,\nerror path = test-matrix row)", BLUE_F, BLUE_L)
a3 = box(600, 160, 200, 100, "2 pi ANALYST\ncompletes the flow card\n(mapping OSB → Camel K YAML)", BLUE_F, BLUE_L, bold=True)
ga = box(850, 165, 170, 90, "GATE A\nengineer approves\nthe flow card", AMB_F, AMB_L, bold=True)
a4 = box(1290, 160, 250, 100, "6 pi IMPLEMENTER\nwrites the Camel K route\n(YAML DSL, *.camel.yaml,\nfrom the approved card)", BLUE_F, BLUE_L, bold=True)
a5 = box(1590, 160, 270, 100, "Camel K integration\nroute.camel.yaml + properties\n(Integration CR / kamel run)", TGREY, BLUE_L)
text(1290, 270, 560, 60, "Implementer rule: may not touch src/test or the card. If a test looks wrong it writes "
     "TEST_DISPUTE.md with OSB evidence and stops.", fs=11, bold=False, fc=GREY)

# Track B
b1 = box(50, 490, 220, 90, "Splunk logs of the flow\n(real messages, 2–4 weeks\nincl. a month-end)", TGREY, GREY)
b2 = box(320, 490, 230, 90, "3 Anonymise (inside GOSI)\nanonymize_logs.py · MASK_KEY\nresidue check = 0 findings", TMINT, MINT)
b3 = box(600, 490, 200, 90, "4 Test cases\none per real transaction\ninput · headers · expected", TMINT, MINT)
b4 = box(850, 490, 210, 90, "5 Expected results\nORIGINAL OSB XQuery on the\nsame inputs (golden runner,\nORACLE.lock)", TMINT, MINT)
b5 = box(1110, 490, 220, 90, "6 pi TESTER\nwrites tests + mocks FIRST\n(fresh context, no route yet)", TMINT, MINT, bold=True)
b6 = box(1380, 470, 480, 130, "Tests and mocks (src/test)\nL1 unit: the YAML route loaded in a Camel test, mock endpoints (no Docker)\n"
         "L2 component: Artemis + WireMock in throwaway containers\nL3 replay: built image against the mock stack\n"
         "DB / DVM / callout / file / mail / security mocks if the card lists them", TGREY, MINT, 12, align="left")
text(50, 600, 1300, 50, "Track B without the OSB source (task 1): anonymise → signature from one example log line → test cases "
     "→ replay against a stand-in flow. Proves data chain and mocks before any migration code exists.", fs=11, bold=False, fc=GREY)
text(1110, 600, 740, 40, "Tester rule: may not touch src/main. Expected files only from OSB (logs, original XQuery, "
     "OSB Test Console); never from the new code (gate G7, G10).", fs=11, bold=False, fc=GREY)

# Joint verification
v1 = box(300, 800, 380, 110, "7 VERIFY (deterministic, no AI)\nverify_flow.sh: G1 build · G2 endpoints · G3 rules\n"
         "G4 unit/golden/contract · G5 containers · G6 matrix\nG7 provenance · G8 mutation · G10 oracle lock", INK, INK, 12, fc="#FFFFFF")
fx = box(730, 800, 250, 110, "Fix loop (max 3)\nred gate → pi implementer fixes\nsrc/main only; tests unchanged", BLUE_F, BLUE_L)
rv = box(1030, 800, 220, 110, "8 pi REVIEWER\nread-only review\nREVIEW.md, MIGRATION_RECORD", TGREY, GREY, bold=True)
gb = box(1300, 805, 190, 100, "GATE B\nsecond engineer signs\nall gates green", AMB_F, AMB_L, bold=True)
sh = box(1540, 800, 320, 110, "9 Shadow run in UAT (acceptance)\nsame live events to OSB and Camel K;\nonly OSB's result counts;\ncompare → cutover", TGREY, GREY)
text(30, 740, 900, 26, "JOINED ONLY HERE: the route from track A runs against the tests and mocks from track B", fs=15)

for s, t in ((a1, a2), (a2, a3), (a3, ga)):
    edge(s, t, BLUE_L)
edge(ga, b5, AMB_L, "approved card", ports="exitX=0.5;exitY=1;entryX=0.5;entryY=0;")
edge(ga, a4, AMB_L, "approved card")
edge(a4, a5, BLUE_L)
edge(a1, b4, GREY, "original XQuery", dashed=1, ports="exitX=0.75;exitY=1;entryX=0.5;entryY=0;")
for s, t in ((b1, b2), (b2, b3), (b3, b4), (b4, b5), (b5, b6)):
    edge(s, t, "#0E6B50")
edge(a5, v1, BLUE_L, "route (track A)", ports="exitX=1;exitY=0.5;entryX=0.25;entryY=0;", points=((1890, 210), (1890, 785), (395, 785)))
edge(b6, v1, "#0E6B50", "tests + mocks (track B)", ports="exitX=0.5;exitY=1;entryX=0.75;entryY=0;", points=((1620, 700), (585, 700)))
edge(v1, fx, "#C0392B", "red")
edge(fx, v1, BLUE_L, "fixed", ports="exitX=0.5;exitY=1;entryX=0.5;entryY=1;", points=((855, 935), (490, 935)))
edge(v1, rv, "#0E6B50", "all green", ports="exitX=0.75;exitY=0;entryX=0.5;entryY=0;", points=((585, 790), (1140, 790)))
edge(rv, gb, GREY)
edge(gb, sh, AMB_L)

xml = ('<mxfile host="app.diagrams.net"><diagram id="workflow" name="OSB to Camel K workflow">'
       f'<mxGraphModel dx="1600" dy="900" grid="0" gridSize="10" page="1" pageWidth="{W}" pageHeight="980" pageScale="1" math="0" shadow="0">'
       '<root><mxCell id="0"/><mxCell id="1" parent="0"/>' + "".join(cells) + "</root></mxGraphModel></diagram></mxfile>")
out = Path(__file__).with_name("OSB_CamelK_Workflow.drawio")
out.write_text(xml.replace("\\n", "&#10;"), encoding="utf-8")
print("wrote", out)
